/* Offline integration of the actual latest DEBUGLIB package and hosted mods. */
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const JSZip = require('../vendor/jszip.min.js');
require('../v21-export.js');
const v = globalThis.VisualEncountersV21;
(async () => {
    const html = fs.readFileSync(path.join(__dirname,'../index.html'),'utf8');
    const start = html.indexOf('const enemyDictionary = [');
    const end = html.indexOf('];',start);
    assert.ok(start > 0 && end > start);
    const dictionary = new Function('return ' + html.slice(html.indexOf('[',start),end+1))();
    const zip = await JSZip.loadAsync(fs.readFileSync(path.join(__dirname,'../mods/ezencounters-v21-base.zip')));
    const entry = await zip.file('entry.lua').async('string');
    assert.ok(zip.file('AirManHPV3/entry.lua'));
    assert.ok(zip.file('RollDEBUGLIB_HP/entry.lua'));
    const aliases = [...v.packageAliases(entry)];
    assert.equal(aliases.length, 131, 'full package supports 131 aliases');
    const missing = aliases.filter(a => !dictionary.some(x => x.name === a));
    assert.deepEqual(missing, [], 'all available aliases selectable in editor');
    const local = v.localBattleAliases(entry);
    assert.deepEqual([...local].sort(), ['AirMan','Roll']);
    const plan = v.collectModDownloads(aliases, dictionary, local);
    assert.deepEqual(plan.unresolved, []);
    for (const name of plan.files) assert.ok(fs.existsSync(path.join(__dirname,'../mods',name)),name);
    assert.ok(plan.files.length >= 115, 'full catalogue pulls hosted character mods');
    const identity = v.mapIdentity('DEBUGLIB');
    const focused = v.patchBattleEntry(entry, identity, ['Bladia','Roll']);
    const table = text => text.match(/local liberation_aliases = \{([\s\S]*?)\n\}/)[1];
    assert.match(table(focused), /Bladia = true/);
    assert.match(table(focused), /Roll = true/);
    assert.doesNotMatch(table(focused), /BigBrute = true/);
    const all = v.patchBattleEntry(entry, identity, aliases);
    assert.equal((table(all).match(/[A-Za-z_]\w* = true,/g)||[]).length,131);
    assert.ok(all.includes('local package_name = "ezencounters_liberation_debuglib"'));
    assert.match(all, /Engine\.define_character\("com\.keristero\.char\.Roll\.DEBUGLIB_DYNAMIC_HP_V1"/);
    assert.match(all, /Engine\.define_character\("com\.keristero\.char\.AirMan\.DEBUGLIB_HP_V3"/);
    console.log('PASS: 131 aliases, full+focused dependencies, local character definitions, hosted mod availability');
})().catch(error => {console.error(error);process.exitCode=1;});
