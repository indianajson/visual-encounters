'use strict';
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict');
const root=path.join(__dirname,'..');
const sandbox={window:{},document:{readyState:'loading',addEventListener(){}}};
vm.createContext(sandbox);
vm.runInContext(fs.readFileSync(path.join(root,'attack-workshop.js'),'utf8'),sandbox);
vm.runInContext(fs.readFileSync(path.join(root,'liberation-editor.js'),'utf8'),sandbox);
const d=sandbox.window.VisualEncountersEditorDiagnostics;
const data={texture_path:'/server/assets/npcs/prog.png',animation_path:'/server/assets/npcs/prog.animation',
 idle_animation_prefix:'IDLE',attack_animation_prefix:'ATTACK',hold_animation_prefix:'HOLD',
 health:100,max_health:240,eight_direction_animations:false};
let text=d.templateModule('MyBot',data);
assert(text.includes('eight_direction_animations = false'));
assert(text.includes('idle_animation_prefix = "IDLE"'));
assert(text.includes('attack_animation_prefix = "ATTACK"'));
assert(!text.includes('attack_damage'));
assert(!text.includes('attack_texture'));
const old={MyBot:{...data,ai_type:'simple_charge',attack_damage:'25',attack_texture:'/server/assets/attack.png',attack_animation_path:'/server/assets/attack.animation',attack_effect_animation:'ANIMATE'}};
const attacks={};
assert.equal(d.migrateLegacyEnemyAttackFields(old,attacks),1);
assert.equal(old.MyBot.attack_damage,undefined);
assert.equal(old.MyBot.attack_texture,undefined);
assert.equal(old.MyBot.attack_template,'MyBot_Attack');
assert.equal(attacks.MyBot_Attack.attack_damage,25);
assert.equal(attacks.MyBot_Attack.attack_texture,'/server/assets/attack.png');
assert.equal(d.migrateLegacyEnemyAttackFields(old,attacks),0,'Migration should be idempotent');
let bundle=d.requiredCustomAttackTemplates(old,attacks);
assert.deepEqual(Object.keys(bundle),['MyBot_Attack']);
attacks.MyBot_Attack.attack_animation_prefix='ANIM';attacks.MyBot_Attack.idle_animation_prefix='STANDBY';
assert.equal(d.migrateLegacyAttackBotAnimations(old,attacks),1);
assert.equal(old.MyBot.attack_animation_prefix,'ATTACK','Do not overwrite authored bot prefix');
assert.equal(old.MyBot.idle_animation_prefix,'IDLE');
assert.equal(attacks.MyBot_Attack.attack_animation_prefix,undefined);
assert.equal(attacks.MyBot_Attack.idle_animation_prefix,undefined);
const other={Unassigned:{ai_type:'ranged'}};
const notlinked={Loose:{runtime:'existing_ai',ai_type:'ranged',attack_animation_prefix:'CHARGE'}};
assert.equal(d.migrateLegacyAttackBotAnimations(other,notlinked),0);
assert.equal(notlinked.Loose.attack_animation_prefix,'CHARGE','Keep legacy prefix until it has a bot recipient');
assert.throws(()=>d.requiredCustomAttackTemplates({Bad:{attack_template:'Missing'}},{}),/Import.*attack JSON\/ZIP|missing Attack Template/i);
console.log('PASS: enemy Lua ownership, old project migration, non-destructive animation prefix migration and dependency checks');
